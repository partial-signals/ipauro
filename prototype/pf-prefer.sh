#!/bin/bash
#
# pf-prefer.sh — force an interface-unaware UDP protocol (default: Ableton Link,
# udp/20808 + multicast 224.76.78.75 / ff12::8080) onto a chosen "audio transport"
# interface by blocking its traffic on EVERY OTHER interface via pf.
#
# This is the deterministic answer to "make Link choose the USB/TB wire": you don't
# persuade the app, you constrain reachability so the preferred segment is the only
# path its packets can take. Peers still see each other over WiFi for everything
# else (SSH, your iroh control plane, etc.) — only the audio port is scoped.
#
# Reversible: `off` restores /etc/pf.conf and pf's original enabled/disabled state.
# Run as root.
set -euo pipefail

PREFER="${PREFER:-bridge90}"     # default audio-transport interface (a hub binds the bridge);
                                 # override per-call: `on <iface...>`
PORT="${PORT:-20808}"            # Ableton Link control port
CONF="/tmp/pf-prefer-${PREFER}.conf"
STATE="/tmp/pf-prefer.state"
WATCHDOG="/tmp/pf-prefer.watchdog"
ANCHOR_TAG="audiopref"

# fail-safe: never leave the audio protocol blocked if the caller dies. A TTL
# watchdog restores /etc/pf.conf after N seconds unless renewed (another `on`) or
# cancelled (`off`). The shipping app should instead tie the scope to its lifecycle.
clear_watchdog() { [ -f "$WATCHDOG" ] && kill "$(cat "$WATCHDOG")" 2>/dev/null; rm -f "$WATCHDOG"; }

gen_conf() {
  # Allow-list model (supports MULTIPLE preferred interfaces, e.g. a relay with two
  # USB links): pass-quick the audio port on each allowed interface, then block-quick
  # it on everything else, then pass all other traffic. `quick` short-circuits, so an
  # allowed interface wins before the catch-all block. lo0 skipped (local loopback).
  {
    echo "# $ANCHOR_TAG: scope udp/$PORT to [$PREFER] (generated by pf-prefer.sh)"
    echo "set skip on lo0"
    for ifc in $PREFER; do
      echo "pass quick on $ifc proto udp from any to any port $PORT"
      echo "pass quick on $ifc proto udp from any port $PORT to any"
    done
    echo "block drop quick proto udp from any to any port $PORT"
    echo "block drop quick proto udp from any port $PORT to any"
    echo "pass"
  } > "$CONF"
}

count_on() { # interface, seconds
  timeout "${2:-5}" /usr/sbin/tcpdump -ni "$1" "udp port $PORT" 2>/dev/null | grep -c . || true
}

case "${1:-}" in
  on)
    shift || true                    # drop "on"; remaining = interface allow-list [+ --ttl N]
    TTL=0; ifaces=""
    while [ "$#" -gt 0 ]; do
      case "$1" in
        --ttl) TTL="${2:-0}"; shift 2 2>/dev/null || shift ;;
        *)     ifaces="$ifaces $1"; shift ;;
      esac
    done
    ifaces="$(echo "$ifaces" | xargs)"
    if [ -n "$ifaces" ]; then PREFER="$ifaces"; fi   # e.g. `on en9 en12` or `on en4 --ttl 300`
    CONF="/tmp/pf-prefer-$(echo "$PREFER" | tr ' ' '-').conf"
    /sbin/pfctl -s info 2>/dev/null | grep -q 'Status: Enabled' \
      && echo enabled > "$STATE" || echo disabled > "$STATE"
    gen_conf
    /sbin/pfctl -f "$CONF" >/dev/null 2>&1
    /sbin/pfctl -e >/dev/null 2>&1 || true   # already-enabled is fine
    # CRITICAL: pf is stateful. Loading the ruleset does NOT tear down existing
    # flows — pf checks the state table BEFORE rules, so an already-established
    # session keeps flowing and the new block never bites. Flush states so the
    # scope actually applies to live connections. Safe for TCP/SSH here because
    # our trailing `pass` is unrestricted (recreates state on the next packet).
    /sbin/pfctl -F states >/dev/null 2>&1
    echo "[pf-prefer] ON — udp/$PORT now allowed ONLY on $PREFER (blocked elsewhere; states flushed)"
    /sbin/pfctl -s rules 2>/dev/null | grep "$PORT" | sed 's/^/  /'
    clear_watchdog                   # cancel any prior fail-safe; (re)arm below if requested
    if [ "${TTL:-0}" -gt 0 ]; then
      ( sleep "$TTL"; /sbin/pfctl -f /etc/pf.conf >/dev/null 2>&1; \
        /usr/bin/logger -t pf-prefer "TTL ${TTL}s expired — pf restored (fail-safe)" ) &
      echo $! > "$WATCHDOG"
      echo "[pf-prefer]   fail-safe armed: auto-restore in ${TTL}s (rerun 'on …' to renew, or 'off')"
    fi
    ;;
  off)
    clear_watchdog
    /sbin/pfctl -f /etc/pf.conf >/dev/null 2>&1 || true
    if [ -f "$STATE" ] && grep -q disabled "$STATE"; then
      /sbin/pfctl -d >/dev/null 2>&1 || true
    fi
    rm -f "$STATE" "$CONF"
    echo "[pf-prefer] OFF — restored /etc/pf.conf and pf's prior state"
    ;;
  status)
    echo "pf status: $(/sbin/pfctl -s info 2>/dev/null | awk '/Status:/{print $2}')"
    echo "audiopref rules:"; /sbin/pfctl -s rules 2>/dev/null | grep "$PORT" | sed 's/^/  /' \
      || echo "  (none loaded)"
    ;;
  verify)
    # Count Link packets per interface over a few seconds. Run with Ableton Live
    # active on the relay and/or a peer so there's Link traffic to observe.
    secs="${2:-6}"
    echo "[pf-prefer] sampling udp/$PORT for ${secs}s per interface..."
    printf "  %-10s WiFi (should be 0 when ON):  " "en0:";      count_on en0 "$secs"
    printf "  %-10s %s (should stay >0):          " "$PREFER:" "$PREFER"; count_on "$PREFER" "$secs"
    echo "  (ON: en0≈0, $PREFER>0 == Link forced onto the wire. OFF: both >0.)"
    ;;
  *) echo "usage: sudo $0 {on <iface...> [--ttl sec] | off | status | verify [seconds]}"; exit 2 ;;
esac
